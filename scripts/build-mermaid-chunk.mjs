/**
 * Regenerate `client.mermaid.js`: the vendored mermaid browser build wrapped in
 * the Client module loader's package-local chunk protocol.
 *
 * The wrapper is what `require.async('./client.mermaid.js')` expects: a chunk
 * registers itself through `window.__ModuleLoader__.load` with the owner package
 * id, its own file name as `chunk`, and a factory whose return value becomes the
 * module's exports. mermaid's browser build is a self-contained IIFE that
 * assigns `globalThis.mermaid`, so the factory captures that assignment, clears
 * the global again, and returns the captured API object.
 *
 * The bundle revision is a hash of `client.js` metadata and chunk URLs carry it
 * as an immutable cache key, so the script touches `client.js` to publish the
 * regenerated chunk under a fresh revision.
 *
 * Usage: node scripts/build-mermaid-chunk.mjs [path/to/mermaid.min.js]
 * Default source: `node_modules/mermaid/dist/mermaid.min.js` under
 * DSH_MERMAID_ROOT, a checkout whose node_modules already carries mermaid.
 */
import { createRequire } from 'node:module'
import { readFileSync, utimesSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const PLUGIN_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OWNER_ID = '@local/dsh-mermaid-viewer'
const CHUNK_FILE = 'client.mermaid.js'

const source = process.argv[2] === undefined
  ? join(
    process.env.DSH_MERMAID_ROOT ?? '/Users/chengyunquan/tools/deepseek-harness',
    'node_modules/mermaid/dist/mermaid.min.js',
  )
  : resolve(process.argv[2])

const body = readFileSync(source, 'utf8')
const notice = readFileSync(join(PLUGIN_DIR, 'NOTICE'), 'utf8').trimEnd()

/**
 * mermaid's browser build closes by publishing its namespace on the global
 * object (`globalThis.__esbuild_esm_mermaid_nm`). Inside a loader factory the
 * namespace variable is function-scoped, so that one global read cannot resolve;
 * dropping the line and returning the namespace's default export directly keeps
 * the API identical and leaves the global object untouched. The build fails loud
 * if a future mermaid build no longer ends this way.
 */
const GLOBAL_PUBLISH = 'globalThis["mermaid"] = globalThis.__esbuild_esm_mermaid_nm["mermaid"].default;'
if (!body.includes(GLOBAL_PUBLISH)) {
  throw new Error(
    `${source} does not end with the expected global publish line; `
    + 'review how this script extracts mermaid\'s API before regenerating the chunk',
  )
}

const chunk = `/**
 * Vendored mermaid browser build (MIT), wrapped as a package-local Client
 * module-loader chunk. Generated by scripts/build-mermaid-chunk.mjs from
 * ${source} — edit that script, not this file.
 *
 * ${notice.replace(/\n/g, '\n * ')}
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(OWNER_ID)},
  chunk: ${JSON.stringify(CHUNK_FILE)},
  factory: (require) => {
    'use strict'
${body.replace(GLOBAL_PUBLISH, '').split('\n').map(line => `    ${line}`).join('\n')}
    return __esbuild_esm_mermaid_nm["mermaid"].default
  },
})
`

writeFileSync(join(PLUGIN_DIR, CHUNK_FILE), chunk)
const now = new Date()
utimesSync(join(PLUGIN_DIR, 'client.js'), now, now)

const require = createRequire(import.meta.url)
const version = require(join(dirname(source), '..', 'package.json')).version
console.log(`${CHUNK_FILE}: ${(chunk.length / 1024 / 1024).toFixed(2)} MiB, mermaid ${version}`)
